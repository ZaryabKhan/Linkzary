@Composable
fun LinkzaryTheme(
    userPreferencesManager: UserPreferencesManager? = null,
    // Dynamic color is available on Android 12+
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    val systemInDarkTheme = isSystemInDarkTheme()
    
    // Get theme mode from preferences or default to system
    val themeMode by if (userPreferencesManager != null) {
        userPreferencesManager.themeMode.collectAsState()
    } else {
        androidx.compose.runtime.remember { 
            androidx.compose.runtime.mutableStateOf(ThemeMode.SYSTEM) 
        }
    }
    
    val darkTheme = when (themeMode) {
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
        ThemeMode.SYSTEM -> systemInDarkTheme
    }
    
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            // Make status bar transparent for edge-to-edge experience
            window.statusBarColor = android.graphics.Color.TRANSPARENT
            // Set status bar icons to be visible based on theme
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}